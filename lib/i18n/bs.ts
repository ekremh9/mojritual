function jeJednina(broj: number): boolean {
  return broj % 10 === 1 && broj % 100 !== 11;
}

function brojProizvoda(broj: number): string {
  return `${broj} ${jeJednina(broj) ? 'proizvod' : 'proizvoda'}`;
}

